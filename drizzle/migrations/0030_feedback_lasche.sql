CREATE OR REPLACE FUNCTION public.product_feedback_notify_done(p_feedback public.product_feedback, p_ticket_no bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_text   text;
  v_snip   text;
  v_ticket text := 'FB-' || lpad(p_ticket_no::text, 4, '0');
  v_du     boolean;
BEGIN
  IF p_feedback.user_id IS NULL OR p_feedback.user_notified_at IS NOT NULL THEN
    RETURN false;
  END IF;
  v_text := regexp_replace(btrim(p_feedback.message), '\s+', ' ', 'g');
  v_snip := left(v_text, 80) || CASE WHEN char_length(v_text) > 80 THEN '…' ELSE '' END;
  v_du := public.has_role(p_feedback.user_id, 'recruiter') OR public.has_role(p_feedback.user_id, 'admin');
  INSERT INTO public.notifications (user_id, type, title, message, related_type, related_id)
  VALUES (
    p_feedback.user_id,
    'feedback_done',
    CASE WHEN v_du THEN 'Dein Feedback ist umgesetzt' ELSE 'Ihr Feedback ist umgesetzt' END,
    CASE WHEN v_du
      THEN format('Danke für deinen Hinweis „%s“ (%s). Das ist jetzt live.', v_snip, v_ticket)
      ELSE format('Danke für Ihren Hinweis „%s“ (%s). Das ist jetzt live.', v_snip, v_ticket)
    END,
    'feedback',
    p_feedback.id
  );
  RETURN true;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Feedback-Nachricht nicht angelegt: %', SQLERRM;
  RETURN false;
END;
$$;
REVOKE ALL ON FUNCTION public.product_feedback_notify_done(public.product_feedback, bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.product_feedback_notify_done(public.product_feedback, bigint) FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.product_feedback_before_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    NEW.status_changed_at := now();
    IF NEW.status = 'done' AND public.product_feedback_notify_done(NEW, NEW.ticket_no) THEN
      NEW.user_notified_at := now();
    END IF;
  END IF;
  IF NEW.status <> 'duplicate' AND OLD.status = 'duplicate' THEN
    NEW.duplicate_of := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_product_feedback_before_update ON public.product_feedback;
CREATE TRIGGER trg_product_feedback_before_update
  BEFORE UPDATE ON public.product_feedback
  FOR EACH ROW
  EXECUTE FUNCTION public.product_feedback_before_update();

CREATE OR REPLACE FUNCTION public.product_feedback_after_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor uuid := auth.uid();
  d       public.product_feedback;
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
    VALUES (NEW.id, v_actor, 'status', jsonb_build_object('from', OLD.status, 'to', NEW.status));
  END IF;
  IF NEW.priority IS DISTINCT FROM OLD.priority THEN
    INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
    VALUES (NEW.id, v_actor, 'priority', jsonb_build_object('from', OLD.priority, 'to', NEW.priority));
  END IF;
  IF NEW.assignee_id IS DISTINCT FROM OLD.assignee_id THEN
    INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
    VALUES (NEW.id, v_actor, 'assignee', jsonb_build_object('from', OLD.assignee_id, 'to', NEW.assignee_id));
  END IF;
  IF NEW.duplicate_of IS DISTINCT FROM OLD.duplicate_of AND NEW.duplicate_of IS NOT NULL THEN
    INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
    VALUES (NEW.id, v_actor, 'duplicate', jsonb_build_object(
      'into', NEW.duplicate_of,
      'into_ticket', (SELECT ticket_no FROM public.product_feedback WHERE id = NEW.duplicate_of)));
    INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
    VALUES (NEW.duplicate_of, v_actor, 'duplicate', jsonb_build_object('merged', NEW.id, 'merged_ticket', NEW.ticket_no));
  END IF;
  IF NEW.criteria_done IS DISTINCT FROM OLD.criteria_done THEN
    INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
    VALUES (NEW.id, v_actor, 'criteria', jsonb_build_object('done', to_jsonb(NEW.criteria_done)));
  END IF;

  IF NEW.status = 'done' AND OLD.status IS DISTINCT FROM 'done' THEN
    IF NEW.user_notified_at IS NOT NULL AND OLD.user_notified_at IS NULL THEN
      INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
      VALUES (NEW.id, v_actor, 'notified', jsonb_build_object('ticket', NEW.ticket_no));
    END IF;
    FOR d IN
      SELECT * FROM public.product_feedback
       WHERE duplicate_of = NEW.id AND user_id IS NOT NULL AND user_notified_at IS NULL
    LOOP
      IF public.product_feedback_notify_done(d, NEW.ticket_no) THEN
        UPDATE public.product_feedback SET user_notified_at = now() WHERE id = d.id;
        INSERT INTO public.product_feedback_events (feedback_id, actor_id, kind, data)
        VALUES (NEW.id, v_actor, 'notified', jsonb_build_object('ticket', d.ticket_no));
      END IF;
    END LOOP;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_product_feedback_after_update ON public.product_feedback;
CREATE TRIGGER trg_product_feedback_after_update
  AFTER UPDATE ON public.product_feedback
  FOR EACH ROW
  EXECUTE FUNCTION public.product_feedback_after_update();

CREATE OR REPLACE FUNCTION public.my_feedback()
RETURNS TABLE (ticket_no bigint, summary text, status text, created_at timestamptz)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT f.ticket_no,
         left(split_part(btrim(f.message), E'\n', 1), 80),
         CASE WHEN f.status = 'duplicate' THEN coalesce(m.status, f.status) ELSE f.status END,
         f.created_at
    FROM public.product_feedback f
    LEFT JOIN public.product_feedback m ON m.id = f.duplicate_of
   WHERE f.user_id = auth.uid()
   ORDER BY f.created_at DESC
   LIMIT 20;
$$;
REVOKE ALL ON FUNCTION public.my_feedback() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.my_feedback() FROM anon;
GRANT EXECUTE ON FUNCTION public.my_feedback() TO authenticated;

CREATE OR REPLACE FUNCTION public.feedback_team()
RETURNS TABLE (user_id uuid, name text, email text)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin') THEN
    RETURN;
  END IF;
  RETURN QUERY
    SELECT DISTINCT ON (r.user_id) r.user_id, p.full_name, p.email
      FROM public.user_roles r
      LEFT JOIN public.profiles p ON p.user_id = r.user_id
     WHERE r.role = 'admin'
     ORDER BY r.user_id;
END;
$$;
REVOKE ALL ON FUNCTION public.feedback_team() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.feedback_team() FROM anon;
GRANT EXECUTE ON FUNCTION public.feedback_team() TO authenticated;

