CREATE TABLE IF NOT EXISTS public.product_feedback (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_no             bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  created_at            timestamptz NOT NULL DEFAULT now(),
  source                text NOT NULL DEFAULT 'app' CHECK (source IN ('app', 'intake')),
  area                  text CHECK (area IN ('client', 'recruiter', 'intake', 'admin', 'other')),
  user_id               uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reporter_role         text CHECK (reporter_role IN ('client', 'recruiter', 'admin', 'guest')),
  reporter_name         text,
  reporter_email        text,
  reporter_company      text,
  intake_link_id        uuid REFERENCES public.intake_links(id) ON DELETE SET NULL,
  intake_draft_id       uuid REFERENCES public.intake_drafts(id) ON DELETE SET NULL,
  kind                  text CHECK (kind IN ('bug', 'unclear', 'idea', 'praise')),
  severity              text CHECK (severity IN ('blocker', 'annoying', 'minor')),
  message               text NOT NULL CHECK (char_length(btrim(message)) BETWEEN 3 AND 5000),
  marks                 jsonb NOT NULL DEFAULT '[]'::jsonb,
  blackout_count        integer NOT NULL DEFAULT 0,
  page_path             text,
  page_title            text,
  route_pattern         text,
  source_file           text,
  viewport              jsonb,
  user_agent            text,
  app_version           text,
  console_errors        jsonb NOT NULL DEFAULT '[]'::jsonb,
  network_errors        jsonb NOT NULL DEFAULT '[]'::jsonb,
  breadcrumbs           jsonb NOT NULL DEFAULT '[]'::jsonb,
  screenshot_path       text,
  crop_paths            text[] NOT NULL DEFAULT '{}',
  screenshot_note       text,
  screenshot_deleted_at timestamptz,
  title                 text,
  ai_brief              jsonb,
  ai_status             text NOT NULL DEFAULT 'pending'
                        CHECK (ai_status IN ('pending', 'done', 'failed')),
  ai_error              text,
  ai_model              text,
  ai_generated_at       timestamptz,
  priority              text CHECK (priority IN ('p0', 'p1', 'p2', 'p3')),
  status                text NOT NULL DEFAULT 'new'
                        CHECK (status IN ('new', 'in_progress', 'built', 'done', 'dismissed', 'duplicate')),
  duplicate_of          uuid REFERENCES public.product_feedback(id) ON DELETE SET NULL,
  assignee_id           uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  criteria_done         integer[] NOT NULL DEFAULT '{}',
  status_changed_at     timestamptz,
  user_notified_at      timestamptz,
  CONSTRAINT product_feedback_duplicate_needs_target
    CHECK (status <> 'duplicate' OR duplicate_of IS NOT NULL),
  CONSTRAINT product_feedback_not_own_duplicate
    CHECK (duplicate_of IS NULL OR duplicate_of <> id)
);

