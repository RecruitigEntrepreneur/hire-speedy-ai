import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../',import.meta.url);
const subsets=['latin','latin-ext','cyrillic','greek'];
const fonts=subsets.map(s=>readFileSync(new URL(`node_modules/@fontsource/noto-sans/files/noto-sans-${s}-400-normal.woff`,root)).toString('base64'));
writeFileSync(new URL('supabase/functions/_shared/recruiter-contract-fonts.ts',root),'// Noto Sans 5.2.6, SIL OFL 1.1; generated by scripts/bundle-recruiter-fonts.mjs.\nexport const CONTRACT_FONTS = '+JSON.stringify(fonts)+';\n');
writeFileSync(new URL('contracts/recruiter/NOTO-SANS-LICENSE.txt',root),readFileSync(new URL('node_modules/@fontsource/noto-sans/LICENSE',root)));
